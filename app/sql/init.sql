-- 3. Normalización a tus tablas finales
-- 3.1 Supervisores
INSERT INTO supervisors (name)
SELECT DISTINCT supervisor FROM raw_data;

-- 3.2 Merchandisers (vinculado al supervisor)
INSERT INTO merchandisers (name, supervisor_id)
SELECT DISTINCT r.repartidor, s.id
FROM raw_data r
JOIN supervisors s ON s.name = r.supervisor;

-- 3.3 Mercados
INSERT INTO markets (name)
SELECT DISTINCT mercado FROM raw_data;

-- 3.4 Clientes
INSERT INTO customers (code, customer_name, category, market_id, latitude, longitude, visit_duration_minutes, merchandiser_id)
SELECT 
    r.codigo, r.cliente, r.categoria, m.id, r.lat, r.lon, r.duracion, me.id
FROM raw_data r
JOIN markets m ON m.name = r.mercado
JOIN merchandisers me ON me.name = r.repartidor;

-- 3.5 Días de visita (Lunes=0, Martes=1, ..., Sábado=5)
INSERT INTO customer_visit_days (customer_id, day_of_week)
SELECT c.id, d.day_of_week
FROM customers c
JOIN raw_data r ON r.codigo = c.code
CROSS JOIN LATERAL (
    VALUES (0, r.lunes), (1, r.martes), (2, r.miercoles), (3, r.jueves), (4, r.viernes), (5, r.sabado)
) AS d(day_of_week, flag)
WHERE d.flag = 1;

-- Limpieza opcional
DROP TABLE raw_data;

